const ENRICHED_BASE_UNITS: Unit[] = BASE_CURRICULUM_UNITS.map((unit) => {
  const fourthLesson = UNIT_FOURTH_LESSONS[unit.id];
  const section: 1 | 2 = unit.order <= 4 ? 1 : 2;
  return {
    ...unit,
    section,
    lessons: fourthLesson ? [...unit.lessons, fourthLesson] : unit.lessons,
  };
});

export const CURRICULUM_UNITS: Unit[] = [
  ...ENRICHED_BASE_UNITS,
  ...EXPLORER_UNITS,
  ...TRAVELER_A_UNITS,
  ...TRAVELER_B_UNITS,
  ...TRAILBLAZER_UNITS,
];

export function getAllLessons() {
  return CURRICULUM_UNITS.flatMap((unit) => unit.lessons);
}

export function findLessonById(lessonId: string) {
  for (const unit of CURRICULUM_UNITS) {
    const lesson = unit.lessons.find((l) => l.id === lessonId);
    if (lesson) {
      return { unit, lesson };
    }
  }
  return null;
}
